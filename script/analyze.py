#!/usr/bin/env python3
"""Turn results/raw.txt into results/summary.md and verify every claim.

Usage: script/analyze.py RAW SUMMARY
Exits with status 1 if any check fails. Standard library only.
"""

import re
import sys
from collections import defaultdict

VERSIONS = ["0.8.38", "0.8.39"]
OLD, NEW = VERSIONS
MODES = ["legacy", "legacy + optimizer", "via-IR", "via-IR + optimizer"]
LAYOUTS = ["ArrayFirst", "DataFirst", "Sandwich"]
FORMS = ["struct", "array"]
FUZZ_METRICS = ["copies", "corrupted", "expectedFields", "zeroed", "dropped", "nonZeroWrong", "extra",
                "sourceNodes", "maxSourceNodes"]
TARGETED = {"A": "root = root.children[0] (write-up example)",
            "B": "same overlap via storage pointer + mapping key",
            "C": "roots = roots[0].children",
            "D": "value field first, root -> {1} -> [{2}, {3}]"}
# Correct result of test G: root = {1, [{2, [{4}, {5}]}, {3, [{6}]}]}
EXPECTED_G = {
    "root.data": 1, "root.children.length": 2,
    "root.c0.data": 2, "root.c0.children.length": 2,
    "root.c0.c0.data": 4, "root.c0.c0.children.length": 0,
    "root.c0.c1.data": 5, "root.c0.c1.children.length": 0,
    "root.c1.data": 3, "root.c1.children.length": 1,
    "root.c1.c0.data": 6, "root.c1.c0.children.length": 0,
}


def parse(path):
    forge = "unknown"
    runs = defaultdict(lambda: {"log": {}, "gas": defaultdict(dict), "build": None})
    run = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("forge Version"):
            forge = line.split(":", 1)[1].strip()
        elif m := re.match(r"^===== solc (\S+) \| (.+) =====$", line):
            run = runs[(m[1], m[2])]
        elif m := re.match(r"^\s+build: (\S+) \| evm (\S+) \| viaIR (\S+) \| optimizer (\S+) runs (\d+)$", line):
            run["build"] = {"version": m[1], "evm": m[2], "via_ir": m[3] == "True",
                            "optimizer": m[4] == "True", "runs": int(m[5])}
        elif m := re.match(r"^\s+[EJ] (warm|cold) gas: nested structs in target (\d+) (\d+)$", line):
            run["gas"][m[1]][int(m[2])] = int(m[3])
        elif m := re.match(r"^\s+([A-Z]) (.+) (\d+)$", line):
            run["log"][f"{m[1]} {m[2]}"] = int(m[3])
    return forge, runs


def fit(points):
    xs, ys = zip(*sorted(points.items()))
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    intercept = my - slope * mx
    residual = max(abs(y - (intercept + slope * x)) for x, y in zip(xs, ys))
    return intercept, slope, residual


def mismatches(run, letter):
    out = []
    for key, value in run["log"].items():
        m = re.search(r"\(expect (\d+)\)", key)
        if key.startswith(letter + " ") and m and int(m[1]) != value:
            out.append(key)
    return out


def fuzz(run, layout, form):
    return {k: run["log"].get(f"Z {layout} {form} {k}") for k in FUZZ_METRICS}


def g_tree(run):
    return {k[2:]: v for k, v in run["log"].items() if k.startswith("G ")}


def main(raw_path, out_path):
    forge, runs = parse(raw_path)
    checks = []

    def check(text, ok):
        checks.append((text, bool(ok)))

    md = ["# Results", "",
          "Generated by `script/analyze.py` from the output of `run.sh`. Do not edit by hand.", "",
          f"Foundry: `{forge}`", ""]

    # Builds
    md += ["## Builds", "", "| solc | Build | EVM | via-IR | Optimizer (runs) |", "|---|---|---|---|---|"]
    builds_ok = True
    for v in VERSIONS:
        for mode in MODES:
            b = runs[(v, mode)]["build"]
            want_ir, want_opt = mode.startswith("via-IR"), mode.endswith("optimizer")
            ok = bool(b) and b["version"].startswith(v + "+") and b["via_ir"] == want_ir \
                and b["optimizer"] == want_opt and b["evm"] == "osaka"
            builds_ok &= ok
            md.append(f"| {b['version']} | {mode} | {b['evm']} | {b['via_ir']} | "
                      f"{b['optimizer']} ({b['runs']}) |" if b else f"| {v} | {mode} | missing | | |")
    check("All 8 builds used the intended compiler, pipeline, optimizer setting and EVM version", builds_ok)
    md.append("")

    # Targeted reproductions
    md += ["## 1. Targeted reproductions (A-D)", "",
           f"| Test | Pattern | {OLD} | {NEW} |", "|---|---|---|---|"]
    for letter, text in TARGETED.items():
        old_bad = sum(bool(mismatches(runs[(OLD, m)], letter)) for m in MODES)
        new_bad = sum(bool(mismatches(runs[(NEW, m)], letter)) for m in MODES)
        md.append(f"| {letter} | {text} | corrupted in {old_bad}/4 builds | corrupted in {new_bad}/4 builds |")
        check(f"{letter}: corrupted in every {OLD} build", old_bad == 4)
        check(f"{letter}: correct in every {NEW} build", new_bad == 0)
    md += ["", "Observed values (identical in all four builds of each version):", "",
           f"| Log line | {OLD} | {NEW} |", "|---|---|---|"]
    for key in sorted(k for k in runs[(OLD, MODES[0])]["log"] if k[0] in TARGETED):
        olds = {runs[(OLD, m)]["log"].get(key) for m in MODES}
        news = {runs[(NEW, m)]["log"].get(key) for m in MODES}
        check(f"{key}: identical across builds", len(olds) == 1 and len(news) == 1)
        md.append(f"| `{key}` | {', '.join(map(str, olds))} | {', '.join(map(str, news))} |")
    md.append("")

    # Shallow vs deep
    md += ["## 2. A shallow test passes on corrupted state (G, H)", "",
           "Tree `root{100} -> S{1} -> [A{2} -> [{4}, {5}], B{3} -> [{6}]]`, value field declared first, "
           "copy `root = root.children[0]`.", "",
           f"| Field after the copy | Expected | {OLD} | {NEW} |", "|---|---|---|---|"]
    trees = {v: [g_tree(runs[(v, m)]) for m in MODES] for v in VERSIONS}
    for v in VERSIONS:
        check(f"G: result tree identical in all four {v} builds", all(t == trees[v][0] for t in trees[v]))
    check(f"G: {NEW} result equals the expected tree in every build",
          all(t == EXPECTED_G for t in trees[NEW]))
    for key, want in EXPECTED_G.items():
        o = trees[OLD][0].get(key, "missing")
        n = trees[NEW][0].get(key, "missing")
        md.append(f"| `{key}` | {want} | {o} | {n} |")
    for v in VERSIONS:
        shallow = [runs[(v, m)]["log"].get("H shallow check passes (top value, top length, first child value)")
                   for m in MODES]
        deep = [runs[(v, m)]["log"].get("H deep compare against memory snapshot passes") for m in MODES]
        check(f"H: shallow check passes in every {v} build", shallow == [1] * 4)
        check(f"H: deep comparison {'fails' if v == OLD else 'passes'} in every {v} build",
              deep == ([0] * 4 if v == OLD else [1] * 4))
        md.append("")
        md.append(f"{v}: shallow check (top value, top length, first child value) "
                  f"{'passes' if shallow == [1] * 4 else 'FAILS'}; deep comparison against the memory snapshot "
                  f"{'passes' if deep == [1] * 4 else 'fails' if deep == [0] * 4 else 'MIXED'} (all four builds).")
    md.append("")

    # Random differential test
    md += ["## 3. Random differential test (Z)", ""]
    for v in VERSIONS:
        tables = {m: {(l, f): fuzz(runs[(v, m)], l, f) for l in LAYOUTS for f in FORMS} for m in MODES}
        identical = all(tables[m] == tables[MODES[0]] for m in MODES)
        check(f"Z: identical results in all four {v} builds", identical)
        t = tables[MODES[0]]
        total = {k: sum((t[c][k] or 0) for c in t) for k in FUZZ_METRICS}
        total["maxSourceNodes"] = max((t[c]["maxSourceNodes"] or 0) for c in t)
        md += [f"### {v} (identical in all four builds: {'yes' if identical else 'NO'})", "",
               "| Layout | Form | Copies | Corrupted | Expected fields | Zeroed | Dropped | Non-zero wrong | Extra "
               "| Avg source nodes | Max source nodes |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for (layout, form), r in list(t.items()) + [(("**Total**", ""), total)]:
            avg = r["sourceNodes"] / r["copies"] if r["copies"] else 0
            md.append(f"| {layout} | {form} | {r['copies']} | {r['corrupted']} | {r['expectedFields']} | "
                      f"{r['zeroed']} | {r['dropped']} | {r['nonZeroWrong']} | {r['extra']} | {avg:.1f} | "
                      f"{r['maxSourceNodes']} |")
        md.append("")
        if v == OLD:
            check(f"Z: {OLD} corrupts copies in every layout and form",
                  all((r["corrupted"] or 0) > 0 for r in t.values()))
            check(f"Z: {OLD} never produced a wrong non-zero value or an extra node",
                  total["nonZeroWrong"] == 0 and total["extra"] == 0)
        else:
            check(f"Z: {NEW} result equals the memory snapshot in every copy",
                  total["corrupted"] == 0 and total["zeroed"] + total["dropped"] + total["nonZeroWrong"]
                  + total["extra"] == 0)

    # Gas
    md += ["## 4. Cost of the fix (E warm, J cold)", "",
           "Non-overlapping copy of a node with one leaf child onto a target holding N leaf nodes, "
           "N = 0, 10, ..., 100. Execution gas measured with `gasleft()` around the assignment (refunds and "
           "transaction base cost excluded). Delta = 0.8.39 - 0.8.38, same build and N; least-squares fit "
           "`delta = fixed + perStruct * N`.", "",
           "| Build | 0.8.38 gas, N = 0 / 100 (warm) | Delta fixed | Delta per nested struct "
           "| Max fit residual | Max abs(warm delta - cold delta) | Delta at N = 100, warm / cold |",
           "|---|---|---|---|---|---|---|"]
    details = []
    for mode in MODES:
        o, n = runs[(OLD, mode)]["gas"], runs[(NEW, mode)]["gas"]
        dw = {x: n["warm"][x] - o["warm"][x] for x in o["warm"]}
        dc = {x: n["cold"][x] - o["cold"][x] for x in o["cold"]}
        wi, ws, wr = fit(dw)
        ci, cs, cr = fit(dc)
        same = max(abs(dw[x] - dc[x]) for x in dw)
        check(f"Gas ({mode}): delta identical with warm and cold storage for every N", same == 0)
        check(f"Gas ({mode}): delta is linear in the number of nested structs", max(wr, cr) < 1)
        pw, pc = 100 * dw[100] / o["warm"][100], 100 * dc[100] / o["cold"][100]
        md.append(f"| {mode} | {o['warm'][0]:,} / {o['warm'][100]:,} | +{wi:,.0f} | +{ws:,.1f} | {max(wr, cr):.2f} "
                  f"| {same} | +{pw:.1f}% / +{pc:.1f}% |")
        details += [f"**{mode}**", "", "| N | 0.8.38 warm | 0.8.39 warm | Delta warm | 0.8.38 cold | 0.8.39 cold "
                    "| Delta cold |", "|---|---|---|---|---|---|---|"]
        for x in sorted(dw):
            details.append(f"| {x} | {o['warm'][x]} | {n['warm'][x]} | +{dw[x]} | {o['cold'][x]} | "
                           f"{n['cold'][x]} | +{dc[x]} |")
        details.append("")
    md += ["", "<details><summary>Raw gas per N</summary>", ""] + details + ["</details>", ""]

    # Depth
    md += ["## 5. Depth limit (K)", "",
           "Target: linear chain of depth d (one child per node). Source: empty node, no overlap. "
           "Linear scan d = 1..260, 200M gas per attempt. The failure reason is read from the `-vvvv` trace.", "",
           f"| Build | {OLD} deepest successful copy | {NEW} deepest successful copy | Failures ({OLD} / {NEW}) | "
           f"Of which StackOverflow ({OLD} / {NEW}) |", "|---|---|---|---|---|"]
    for mode in MODES:
        row = []
        for v in VERSIONS:
            lg = runs[(v, mode)]["log"]
            last, first = lg["K scan: last successful depth"], lg["K scan: first failing depth"]
            fails, after = lg["K scan: failures"], lg["K scan: successes after first failure"]
            so, other = lg["K trace: StackOverflow failures"], lg["K trace: other failures"]
            check(f"Depth ({v}, {mode}): single threshold, every failure is a StackOverflow",
                  after == 0 and first == last + 1 and fails == 260 - last and so == fails and other == 0)
            row.append((last, fails, so))
        md.append(f"| {mode} | {row[0][0]} | {row[1][0]} | {row[0][1]} / {row[1][1]} | "
                  f"{row[0][2]} / {row[1][2]} |")
    md.append("")

    # Checks
    failed = [c for c in checks if not c[1]]
    md += ["## Checks", "", f"{len(checks) - len(failed)} of {len(checks)} checks pass.", ""]
    md += [f"- {'PASS' if ok else 'FAIL'}: {text}" for text, ok in checks]
    md.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print(f"{len(checks) - len(failed)}/{len(checks)} checks pass; wrote {out_path}")
    for text, _ in failed:
        print(f"FAIL: {text}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1], sys.argv[2]))
